package _01_Basic_in_Java;

public class arithmeticOperationOnInt {
    public static void main(String[] args) {
        double x = 50;
        double y = 8;
        System.out.println(x+y);
        System.out.println(x-y);
        System.out.println(x*y);
        System.out.println(x/y);
    }
}
